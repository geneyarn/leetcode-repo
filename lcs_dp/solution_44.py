from functools import cache


class Solution:
    def isMatch(self, s: str, p: str) -> bool:
        # Step 1: 压缩连续 *
        compressed = []
        for c in p:
            if c == '*' and compressed and compressed[-1] == '*':
                continue
            compressed.append(c)
        p = ''.join(compressed)
        m, n = len(s), len(p)

        @cache
        def dp(i: int, j: int) -> bool:
            if j == n:
                return i == m

            if i == m:
                return p[j] == '*' and dp(i, j + 1)

            # j < n (i < m or i == m)
            if p[j] == '*':
                return dp(i, j + 1) or (i < m and dp(i + 1, j))
            if i < m and (s[i] == p[j] or p[j] == '?'):
                return dp(i + 1, j + 1)

            return False

        result = dp(0, 0)
        dp.cache_clear()
        return result


